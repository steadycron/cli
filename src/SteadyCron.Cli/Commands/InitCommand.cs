              # - channel: ops-email
              #   trigger: on_n_consecutive
              #   severity: p1
              #   params:
              #     threshold: 3

              # Fire once when the job succeeds again after a period of failure.
              - channel: ops-slack
                trigger: on_recovery
                severity: p3

          # ── Heartbeat monitor ──────────────────────────────────────────────────────
          # YOUR code sends a ping to SteadyCron on each successful run.
          # SteadyCron alerts if no ping arrives within the expected window.
          #
          # Obtain the ping URL after applying:
          #   steadycron jobs get nightly-backup
          - id: nightly-backup
            name: Nightly backup
            kind: heartbeat

            description: Database backup that runs via the production server's cron daemon.
            runbook_url: https://wiki.example.com/runbooks/nightly-backup

            # Use `schedule` (cron) OR `interval` (seconds) — not both.
            schedule: "0 2 * * *"       # expect a ping every night at 02:00
            # interval: 86400           # alternative: expect a ping every 24 hours
            timezone: UTC
            paused: false

            # grace: seconds of extra time allowed after the expected window closes before
            # SteadyCron triggers an alert. Absorbs normal scheduling jitter.
            grace: 600                  # 10-minute grace period

            # stuck_run_detection: alert when a run starts (via the /start ping) but never
            # completes (no /finish or /fail ping within max_run_duration seconds).
            stuck_run_detection: true

            # max_run_duration: maximum expected runtime in seconds.
            # Only meaningful when stuck_run_detection is true.
            max_run_duration: 3600      # 1 hour

            tags:
              - env:production

            rules:
              - channel: ops-email
                trigger: on_missed_heartbeat
                severity: p1
                dedup_window_seconds: 3600   # at most one alert per hour

              - channel: ops-email
                trigger: on_recovery
                severity: p3

        # ── Delivery Shaping ──────────────────────────────────────────────────────────
        # Account-level throttles applied across all jobs. Useful when many jobs fire at
