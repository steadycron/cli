using System.ComponentModel;
using Spectre.Console;
using Spectre.Console.Cli;
using SteadyCron.Cli.Output;

namespace SteadyCron.Cli.Commands;

public sealed class InitSettings : CommandSettings
{
    [CommandOption("--terraform")]
    [Description("Generate a Terraform HCL boilerplate instead of YAML.")]
    public bool Terraform { get; set; }

    [CommandOption("-o|--output-file <PATH>")]
    [Description("Write the boilerplate to a file instead of printing to stdout.")]
    public string? OutputFile { get; set; }
}

/// <summary>`steadycron init` — generates a fully documented boilerplate manifest covering every SteadyCron feature.</summary>
public sealed class InitCommand : Command<InitSettings>
{
    public override int Execute(CommandContext context, InitSettings settings)
    {
        var content = settings.Terraform ? TerraformBoilerplate : YamlBoilerplate;

        if (settings.OutputFile is null)
        {
            Console.Write(content);
            return ExitCodes.Ok;
        }

        if (File.Exists(settings.OutputFile))
        {
            AnsiConsole.MarkupLineInterpolated(
                $"[red]✗[/] File already exists: {settings.OutputFile}. Delete it or choose a different path.");
            return ExitCodes.Error;
        }

        File.WriteAllText(settings.OutputFile, content);

        if (settings.Terraform)
        {
            AnsiConsole.MarkupLineInterpolated(
                $"[green]✓[/] Terraform boilerplate written to [bold]{settings.OutputFile}[/]");
            AnsiConsole.MarkupLine(
                "Run [bold]terraform init && terraform plan[/] to preview, then [bold]terraform apply[/] to provision.");
        }
        else
        {
            AnsiConsole.MarkupLineInterpolated(
                $"[green]✓[/] YAML manifest written to [bold]{settings.OutputFile}[/]");
            AnsiConsole.MarkupLine(
                "Run [bold]steadycron plan steadycron.yaml[/] to preview, then [bold]steadycron apply steadycron.yaml[/] to apply.");
        }

        return ExitCodes.Ok;
    }

    private const string YamlBoilerplate =
